import json
import os
import random
import requests
import time
import pandas as pd

def download_file(url, out_path, max_retries=3):
    if os.path.exists(out_path):
        return True
    
    file_id = url.split('id=')[-1]
    direct_url = f"https://drive.google.com/uc?export=download&id={file_id}"
    
    for attempt in range(max_retries):
        try:
            r = requests.get(direct_url, timeout=15)
            if r.status_code == 200 and 'html' not in r.headers.get('Content-Type', '').lower():
                with open(out_path, 'wb') as f:
                    f.write(r.content)
                return True
            else:
                time.sleep(2)
        except Exception as e:
            time.sleep(2)
            pass
    return False

def main():
    target_count = 247
    os.makedirs('dataset/images', exist_ok=True)
    
    with open('dataset/gdrive_contents.json', encoding='utf-16') as f:
        data = json.load(f)

    # Pneumonia images are mostly .jpeg or .jpg
    pneu_links = [p for p in data if 'pneumonia' in p['path'].lower() and p['path'].endswith(('.png', '.jpeg', '.jpg'))]
    
    random.seed(42)
    random.shuffle(pneu_links)
    
    print(f"Fetching Pneumonia (Target: {target_count})...")
    count = 0
    records = []
    
    # Check already downloaded to resume (should be 0 right now)
    for file in os.listdir('dataset/images'):
        if file.startswith('Pneumonia'):
            count += 1
            records.append({'filename': file, 'label': 'Pneumonia'})
            
    for p in pneu_links:
        if count >= target_count:
            break
        # Save them as .png so the training script data loader can handle them uniformly (or keep as .jpeg, PIL handles both)
        # We will save as .jpeg if it's .jpeg
        ext = '.png'
        if p['path'].endswith('.jpeg'):
            ext = '.jpeg'
        elif p['path'].endswith('.jpg'):
            ext = '.jpg'
            
        filename = f"Pneumonia_{count:04d}{ext}"
        out_path = f"dataset/images/{filename}"
        if download_file(p['url'], out_path):
            count += 1
            records.append({'filename': filename, 'label': 'Pneumonia'})
            if count % 10 == 0:
                print(f"  {count}/{target_count} downloaded for Pneumonia")
                
    print(f"Total Pneumonia obtained: {count}")
    
    # Now we need to append these records to the labels.csv
    # Read the existing labels.csv generated by task-532
    df_existing = pd.read_csv('dataset/labels.csv')
    
    # Remove any existing Pneumonia rows just in case, to avoid duplicates
    df_existing = df_existing[df_existing['label'] != 'Pneumonia']
    
    # Assign 'unknown_N' patient IDs to Pneumonia
    for idx, rec in enumerate(records):
        rec['patientid'] = f"unknown_pneumonia_{idx}"
        
    df_new = pd.DataFrame(records)
    df_final = pd.concat([df_existing, df_new], ignore_index=True)
    
    df_final.to_csv('dataset/labels.csv', index=False)
    print(f"Updated labels.csv with {len(df_final)} total rows.")

if __name__ == '__main__':
    main()
